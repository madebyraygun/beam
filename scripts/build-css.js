/**
 * Write the default theme as a plain stylesheet, dist/css/default.css, for a
 * page to load. The same text is exported as `defaultTheme` for Lit.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const distDir = path.join(here, '..', 'dist', 'css');
fs.mkdirSync(distDir, { recursive: true });

const source = pathToFileURL(path.join(here, '..', 'dist', 'theme', 'default-theme.js')).href;
const { defaultTheme } = await import(source);

const banner = '/* The default theme, generated by scripts/build-css.js from src/theme/default-theme.ts */\n';
fs.writeFileSync(path.join(distDir, 'default.css'), banner + defaultTheme.cssText + '\n');
console.log('  ✓ dist/css/default.css');
